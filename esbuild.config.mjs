import esbuild from "esbuild";
import process from "node:process";
import { builtinModules } from "node:module";
import { copyFileSync, mkdirSync } from "node:fs";
import { homedir } from "node:os";
import { join, resolve } from "node:path";

const banner =
`/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = (process.argv[2] === "production");

// Set OBSIDIAN_PLUGIN_DIR to a vault's plugin folder, e.g.
//   OBSIDIAN_PLUGIN_DIR=~/MyVault/.obsidian/plugins/auto-anki npm run dev
// and every build is copied there, ready for Obsidian to reload.
const PLUGIN_FILES = ["main.js", "manifest.json", "styles.css"];

function pluginDir() {
	const dir = process.env.OBSIDIAN_PLUGIN_DIR;
	if (!dir) return null;
	return resolve(dir.startsWith("~") ? join(homedir(), dir.slice(1)) : dir);
}

const copyToVault = {
	name: "copy-to-vault",
	setup(build) {
		const dir = pluginDir();
		if (!dir) return;
		build.onEnd((result) => {
			if (result.errors.length > 0) return;
			mkdirSync(dir, { recursive: true });
			for (const file of PLUGIN_FILES) copyFileSync(file, join(dir, file));
			console.log(`[copy-to-vault] copied ${PLUGIN_FILES.join(", ")} to ${dir}`);
		});
	},
};

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ["src/main.ts"],
	bundle: true,
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		// Node's own modules (fs, path, …) are provided by Obsidian's desktop app at
		// runtime, so they're left out of the bundle.
		...builtinModules],
	format: "cjs",
	target: "es2021",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	outfile: "main.js",
	plugins: [copyToVault],
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
